#!/usr/bin/env node
// Prepare exact native source bytes for a later authenticated Figma import.
// Creating this file does not modify Figma or claim synchronization.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generatedArtEntries, generatedArtProblems } from './generated-art-contract.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const problems = generatedArtProblems();
if (problems.length) throw Error(problems.join('\n'));
const assets = generatedArtEntries().map(entry => ({ ...entry, base64: readFileSync(join(root, entry.path)).toString('base64') }));
if (assets.length !== 3) throw Error('All three source-pinned native sheets must exist before preparing the import');
const script = `// Pending import into TC0PHGMTCMR6im4hb3CSbF, page 10:2 / runtime bosses 451:4.
// Load figma-use before executing. Do not mark the pack synchronized until
// this result and a fresh remote capture pass the normal figma:check workflow.
const assets = ${JSON.stringify(assets)};
const page = await figma.getNodeByIdAsync('10:2');
if (!page || page.type !== 'PAGE') throw new Error('Expected production page 10:2');
await figma.setCurrentPageAsync(page);
const section = await figma.getNodeByIdAsync('451:4');
if (!section || !('appendChild' in section)) throw new Error('Expected runtime bosses section 451:4');
// Image creation changes no canvas nodes; preflight every image before writing.
const images = [];
for (const asset of assets) {
  const image = figma.createImage(figma.base64Decode(asset.base64));
  const size = await image.getSizeAsync();
  if (image.hash !== asset.sha1 || size.width !== asset.width || size.height !== asset.height) throw new Error(asset.path + ': image bytes or dimensions differ');
  const matches = section.findAllWithCriteria({types:['RECTANGLE']}).filter(node => node.name === asset.path);
  if (matches.length > 1) throw new Error(asset.path + ': duplicate existing sources; inspect before writing');
  images.push({ asset, image, existing: matches[0] });
}
const createdNodeIds = [], mutatedNodeIds = [];
const name = 'RUNTIME / crown-ascendant-v1 — native generated master';
let holder = section.children.find(node => node.type === 'FRAME' && node.name === name);
if (!holder) {
  holder = figma.createFrame(); createdNodeIds.push(holder.id);
  holder.name = name; holder.fills = []; holder.clipsContent = false;
  section.appendChild(holder);
  holder.x = 0;
  holder.y = Math.ceil(Math.max(0, ...section.children.filter(node => node !== holder).map(node => node.y + node.height))) + 96;
  holder.resize(Math.max(...assets.map(asset => asset.width)) + 32, 100);
  holder.layoutMode = 'VERTICAL'; holder.itemSpacing = 24;
  holder.paddingLeft = holder.paddingRight = holder.paddingTop = holder.paddingBottom = 16;
  holder.primaryAxisSizingMode = 'AUTO'; holder.counterAxisSizingMode = 'FIXED';
}
const evidence = [];
for (const { asset, image, existing } of images) {
  let node = existing;
  if (!node) { node = figma.createRectangle(); createdNodeIds.push(node.id); }
  else mutatedNodeIds.push(node.id);
  holder.appendChild(node); node.name = asset.path;
  node.resize(asset.width, asset.height);
  node.fills = [{type:'IMAGE',imageHash:image.hash,scaleMode:'FILL'}];
  node.strokes = []; node.effects = []; node.rotation = 0; node.opacity = 1;
  node.layoutSizingHorizontal = 'FIXED'; node.layoutSizingVertical = 'FIXED';
  node.exportSettings = [{format:'PNG',constraints:{type:'SCALE',value:1}}];
  evidence.push({path:asset.path,nodeId:node.id,imageHash:image.hash,width:node.width,height:node.height,x:node.x,y:node.y});
}
holder.setSharedPluginData('max-native-art', 'source', 'Generated by OpenAI imagegen; immutable sources and recipe in docs/asset-review/crown-ascendant-v1. Native 1x exports, binary alpha, 24 colors; see pack README and atlas.json.');
if (!createdNodeIds.includes(holder.id)) mutatedNodeIds.push(holder.id);
return {createdNodeIds,mutatedNodeIds,sectionId:section.id,holderId:holder.id,assets:evidence};
`;
const output = join(root, 'docs/asset-review/crown-ascendant-v1/import.use-figma.js');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, script);
console.log('Prepared ' + output + '; Figma remains pending import.');
