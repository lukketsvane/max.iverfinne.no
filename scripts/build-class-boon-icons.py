def build():
    directory = ROOT / 'assets/boon-symbols-v1'
    pending_path = ROOT / 'assets/figma-pending.json'
    pending = json.loads(pending_path.read_text())
    for name, rows in GLYPHS.items():
        assert len(rows) == 9 and all(len(row) == 9 for row in rows), name
        image = Image.new('RGBA', (9, 9))
        for y, row in enumerate(rows):
            for x, dot in enumerate(row):
                if dot == '#': image.putpixel((x, y), (255, 255, 255, 255))
        path = directory / (name + '.png')
        image.save(path, optimize=True)
        relative = path.relative_to(ROOT).as_posix()
        entry = dict(path=relative, sha1=hashlib.sha1(path.read_bytes()).hexdigest(), width=9, height=9,
                     note='Class mutation UI glyph; native source in scripts/build-class-boon-icons.py')
        pending['files'] = [e for e in pending['files'] if e['path'] != relative]
        pending['files'].append(entry)
    pending_path.write_text(json.dumps(pending, indent=1) + '\n')
    print('Built 20 native class mutation glyphs.')

if __name__ == '__main__': build()
