#!/usr/bin/env node
// Regenerate read-only connected capture from the actual bundled plugin helpers.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const source = readFileSync(new URL('./plugin-main.js', import.meta.url), 'utf8');
const start = source.indexOf('(function () {');
const marker = "  if (typeof module === 'object' && module.exports) module.exports = ";
const end = source.indexOf(marker), apiEnd = source.indexOf(';\n', end);
if (start < 0 || end < start || apiEnd < end) throw new Error('Plugin helper boundaries changed; inspect before regenerating.');
const api = source.slice(end + marker.length, apiEnd);
if (!api.startsWith('{') || !api.endsWith('}')) throw new Error('Plugin helper API was not found.');
const hash = createHash('sha256').update(source).digest('hex');
const output = `// Generated by build-helpers.mjs from plugin-main.js SHA-256 ${hash}.
// Same capture/validation/bridge helpers; no plugin UI and no Figma mutation.
// Defaults to a bounded structural summary. To request native ART counts/digest,
// prepend const MAX_STUDIO_NATIVE_STAGE = 1; in the authenticated read-only call.
const maxLevelStudio = ${source.slice(start, end)}  return ${api};
})();
if (figma.editorType !== 'figma') throw new Error('Open the configured Figma Design file.');
if (figma.fileKey && figma.fileKey !== maxLevelStudio.FILE) throw new Error('Wrong configured Figma file.');
const page = await figma.getNodeByIdAsync(maxLevelStudio.PAGE);
if (!page || page.type !== 'PAGE') throw new Error('Configured levels page was not found.');
await figma.setCurrentPageAsync(page);
const captured = maxLevelStudio.captureMasterPage(page);
const decoded = maxLevelStudio.decodeMasterRows(captured);
const nativeStage = typeof MAX_STUDIO_NATIVE_STAGE === 'undefined' ? null : MAX_STUDIO_NATIVE_STAGE;
const nativeCapture = nativeStage == null ? null : await maxLevelStudio.captureReview(figma, page, nativeStage, true);
return { page: captured.page, file: captured.file, master: captured.master.id, editor: captured.editor.id,
  sourceKind: captured.sourceKind, production: false,
  rows: captured.rows.map(row => ({id:row.id,name:row.name,stage:row.stage,planes:Object.fromEntries(Object.entries(row.planes).map(([key,plane])=>[key,{id:plane.id,x:plane.x,y:plane.y,width:plane.width,height:plane.height,childCount:plane.children.length}])),registration:decoded.rows.find(item=>item.stage===row.stage)?.registration || null})),
  metadataCharacters: decoded.metadata.length,
  fileKeyObserved: figma.fileKey || null,
  validation: { errors: decoded.errors.slice(0,20), warnings: decoded.warnings.slice(0,20), errorCount:decoded.errors.length, warningCount:decoded.warnings.length, count: captured.rows.length, live: decoded.live, exported: decoded.exported },
  bridge: { projection: decoded.projection, preview: false },
  nativeART: nativeCapture ? {stage:nativeStage,rowId:nativeCapture.nativeART[0].chunk.rowId,totalOperations:nativeCapture.nativeART[0].chunk.totalOperations,chunkSHA1:nativeCapture.nativeART[0].chunkSHA1,captureConsistency:nativeCapture.captureConsistency} : null,
  pluginCodeSHA256: '${hash}', status: 'actual-MASTER-document-capture' };
`;
const file = new URL('./helpers.use-figma.js', import.meta.url);
writeFileSync(file, output);
console.log(`Generated ${fileURLToPath(file)} from plugin ${hash}`);
