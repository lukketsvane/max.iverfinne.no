#!/usr/bin/env node
// Embed the exact shared MASTER decoder in the ordinary desktop Figma plugin.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { decodeMasterRows } from '../../../../scripts/master-levels.mjs';
import nativeCapture from '../../master-levels/art/capture-containers.js';
const source = readFileSync(new URL('./plugin-template.js', import.meta.url), 'utf8');
const token = '__MAX_SHARED_DECODER__';
if (source.split(token).length !== 2) throw new Error('The plugin must contain exactly one shared-decoder token.');
const decoder = decodeMasterRows.toString(), hash = createHash('sha256').update(decoder).digest('hex');
const capture = nativeCapture.captureNativeContainers.toString(), captureHash = createHash('sha256').update(capture).digest('hex');
if (source.split('__MAX_NATIVE_CAPTURE__').length !== 2) throw new Error('The plugin must contain exactly one native-capture token.');
const output = `// Generated by build-plugin.mjs; shared decoder SHA-256 ${hash}; native capture SHA-256 ${captureHash}.\n` + source.replace(token, decoder).replace('__MAX_NATIVE_CAPTURE__', capture);
for (const name of ['plugin-main.js', 'code.js']) writeFileSync(new URL('./' + name, import.meta.url), output);
console.log('Generated executable plugin-main.js and identical code.js with exact shared helpers.');
